import http from 'k6/http';
import { check } from 'k6';
import { sleep } from 'k6';

export let options = {
  vus: 50,           // 50 concurrent virtual users
  duration: '15s',   // 15 seconds test duration
  thresholds: {
    http_req_duration: ['p(95)<2000'],
    http_req_failed: ['rate<0.1']
  }
};

// Configuration - UPDATE THESE VALUES
const BASE_URL = 'https://your-backend.example'; // Replace with your backend URL
const WEBHOOK_URL = `${BASE_URL}/api/payment/phonepe/webhook`;

// Test webhook payload (simulate PhonePe webhook)
const WEBHOOK_PAYLOAD = JSON.stringify({
  event: 'PAYMENT_SUCCESS',
  payload: {
    orderId: 'test-order-123',
    transactionId: 'test-txn-456',
    merchantTransactionId: 'test-merchant-txn-789',
    state: 'COMPLETED',
    amount: 10000, // 100.00 INR in paise
    responseCode: 'PAYMENT_SUCCESS',
    responseMessage: 'Payment successful'
  }
});

// PhonePe signature headers (you'll need to generate these with your actual credentials)
const WEBHOOK_HEADERS = {
  'Content-Type': 'application/json',
  'Authorization': 'PLACEHOLDER_SIGNATURE', // Will be generated by the Node.js script
  'X-Request-ID': `webhook_test_${__VU}_${__ITER}`
};

export default function () {
  const correlationId = `webhook_${__VU}_${__ITER}_${Date.now()}`;
  
  // Send webhook multiple times to test idempotency
  const responses = [];
  
  for (let i = 0; i < 3; i++) {
    const response = http.post(WEBHOOK_URL, WEBHOOK_PAYLOAD, {
      headers: {
        ...WEBHOOK_HEADERS,
        'X-Request-ID': `${correlationId}_${i}`
      }
    });

    responses.push(response);

    check(response, {
      'webhook accepted': (r) => r.status === 200,
      'response time < 2s': (r) => r.timings.duration < 2000,
      'has success message': (r) => {
        try {
          const data = JSON.parse(r.body);
          return data.success === true;
        } catch (e) {
          return false;
        }
      }
    });

    // Small delay between webhook sends
    sleep(0.2);
  }

  // Log results for analysis
  if (responses.length > 1) {
    const allSuccessful = responses.every(r => r.status === 200);
    if (allSuccessful) {
      console.log(`[${correlationId}] All webhook replays accepted - checking for idempotency`);
      
      // In a real test, you would check the database to ensure only one order was created
      // This would require additional API calls to verify the order count
    }
  }

  sleep(0.5);
}

export function handleSummary(data) {
  const totalRequests = data.metrics.http_reqs.values.count;
  const successfulRequests = data.metrics.checks.values.rate * totalRequests;
  
  const summary = {
    'Total Webhook Requests': totalRequests,
    'Successful Webhooks': Math.round(successfulRequests),
    'Success Rate': `${(data.metrics.checks.values.rate * 100).toFixed(2)}%`,
    'Average Response Time': `${data.metrics.http_req_duration.values.avg.toFixed(2)}ms`,
    '95th Percentile': `${data.metrics.http_req_duration.values['p(95)'].toFixed(2)}ms`
  };

  console.log('\n=== WEBHOOK REPLAY TEST RESULTS ===');
  Object.entries(summary).forEach(([key, value]) => {
    console.log(`${key}: ${value}`);
  });

  console.log('\n📋 IMPORTANT: This test only verifies webhook acceptance');
  console.log('🔍 To verify idempotency, check your database for duplicate orders');
  console.log('📊 Expected: Only 1 order should be created despite multiple webhook deliveries');

  return {
    'webhook-replay-test-results.json': JSON.stringify(summary, null, 2)
  };
}
